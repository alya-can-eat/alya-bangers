static const char *const *const tables[LANG_COUNT] = { en, de };

const char *txt_in(int lang, StrId id)
{
    if ((unsigned)id >= S_COUNT)
        return "";
    if (lang < 0 || lang >= LANG_COUNT)
        lang = LANG_EN;
    const char *s = tables[lang][id];
    return s ? s : en[id] ? en[id] : "";
}

const char *txt(StrId id)
{
    return txt_in(i18n_lang, id);
}

const char *lang_name(int lang)
{
    return lang == LANG_DE ? "Deutsch" : "English";
}

StrId i18n_missing(int lang)
{
    for (int id = 1; id < S_COUNT; id++)
        if (tables[lang][id] == NULL)
            return (StrId)id;
    return S_NONE;
}
