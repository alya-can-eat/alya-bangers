#!/usr/bin/env python3
"""Generate arm9/source/eq_tables.h: the equalizer's filters for every gain.

    python3 tools/gen_eq_tables.py > arm9/source/eq_tables.h

Three bands, each a biquad from the RBJ Audio EQ Cookbook at the DS sample
rate (16756991 / 512 Hz): Bass a low shelf, Mid a peak, Treble a high shelf.
For each gain from -12 to +12 dB the five coefficients in Q28 (a0 = 1).
Also cos/sin of a grid of frequencies, so the player can work out the
loudest point of a setting and turn the input down by that much (no clipping).
"""
import math

RATE = 16756991 / 512
GAINS = range(-12, 13)
BANDS = [
    ("Bass", "lowshelf", 120.0, 1.0),     # f0, shelf slope S
    ("Mid", "peak", 1000.0, 0.7),         # f0, Q
    ("Treble", "highshelf", 5000.0, 1.0),
]
Q = 28


def biquad(kind, f0, p, db):
    A = 10 ** (db / 40)
    w0 = 2 * math.pi * f0 / RATE
    cw, sw = math.cos(w0), math.sin(w0)
    if kind == "peak":
        alpha = sw / (2 * p)
        b = [1 + alpha * A, -2 * cw, 1 - alpha * A]
        a = [1 + alpha / A, -2 * cw, 1 - alpha / A]
    else:
        alpha = sw / 2 * math.sqrt((A + 1 / A) * (1 / p - 1) + 2)
        sa = 2 * math.sqrt(A) * alpha
        if kind == "lowshelf":
            b = [A * ((A + 1) - (A - 1) * cw + sa), 2 * A * ((A - 1) - (A + 1) * cw),
                 A * ((A + 1) - (A - 1) * cw - sa)]
            a = [(A + 1) + (A - 1) * cw + sa, -2 * ((A - 1) + (A + 1) * cw), (A + 1) + (A - 1) * cw - sa]
        else:
            b = [A * ((A + 1) + (A - 1) * cw + sa), -2 * A * ((A - 1) + (A + 1) * cw),
                 A * ((A + 1) + (A - 1) * cw - sa)]
            a = [(A + 1) - (A - 1) * cw + sa, 2 * ((A - 1) - (A + 1) * cw), (A + 1) - (A - 1) * cw - sa]
    return [b[0] / a[0], b[1] / a[0], b[2] / a[0], a[1] / a[0], a[2] / a[0]]


def q28(v):
    i = round(v * (1 << Q))
    assert -(1 << 31) <= i < (1 << 31), v
    return i


# frequencies to check for the loudest point: log spaced, 20 Hz .. 16 kHz
NF = 64
FREQS = [20 * (16000 / 20) ** (i / (NF - 1)) for i in range(NF)]

out = []
out.append("// SPDX-License-Identifier: GPL-3.0-or-later")
out.append("//")
out.append("// Generated by tools/gen_eq_tables.py: don't edit.")
out.append("// The equalizer's biquads at 32728.5 Hz, per band and gain (-12..+12 dB):")
out.append("// b0 b1 b2 a1 a2 in Q28 (a0 = 1). " +
           ", ".join(f"{n}: {k} {f:g} Hz" for n, k, f, _ in BANDS) + ".")
out.append("")
out.append("#ifndef DSPLAYER_EQ_TABLES_H__")
out.append("#define DSPLAYER_EQ_TABLES_H__")
out.append("")
out.append("#include <stdint.h>")
out.append("")
out.append(f"#define EQ_Q {Q}")
out.append(f"#define EQ_NF {NF}")
out.append("")
out.append("static const int32_t eq_coef[3][25][5] = {")
for name, kind, f0, p in BANDS:
    out.append(f"    {{   // {name}")
    for db in GAINS:
        c = biquad(kind, f0, p, db)
        out.append("        { " + ", ".join(str(q28(v)) for v in c) + " },  // " + f"{db:+d} dB")
    out.append("    },")
out.append("};")
out.append("")
out.append("// cos(w), sin(w), cos(2w), sin(2w) of the frequencies checked for the loudest point")
out.append("static const float eq_grid[EQ_NF][4] = {")
for f in FREQS:
    w = 2 * math.pi * f / RATE
    vals = ", ".join(f"{v:.9f}f" for v in (math.cos(w), math.sin(w), math.cos(2 * w), math.sin(2 * w)))
    out.append("    { " + vals + " },  // " + f"{f:.0f} Hz")
out.append("};")
out.append("")
out.append("#endif")
print("\n".join(out))
