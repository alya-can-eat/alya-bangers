#!/usr/bin/env python3
"""Generate arm9/source/fold_tables.h: Latin letters without their accents and
in lower case, for search (U+00C0..U+024F and U+1E00..U+1EFF), from Python's
Unicode data.

    python3 tools/gen_fold_tables.py > arm9/source/fold_tables.h
"""
import unicodedata

# letters that don't decompose but have a plain spelling
SPECIAL = {"ß": "ss", "æ": "ae", "Æ": "ae", "œ": "oe", "Œ": "oe", "ø": "o", "Ø": "o", "đ": "d", "Đ": "d",
           "ħ": "h", "Ħ": "h", "ı": "i", "ł": "l", "Ł": "l", "ŋ": "n", "Ŋ": "n", "þ": "th", "Þ": "th",
           "ð": "d", "Ð": "d", "ƒ": "f", "ǝ": "e"}


def base_of(c):
    ch = chr(c)
    if ch in SPECIAL:
        return SPECIAL[ch]
    d = unicodedata.normalize("NFD", ch)
    if d[0].isascii() and d[0].isalpha():
        return d[0].lower()
    return None


out = ["// Generated by tools/gen_fold_tables.py. Do not edit.", ""]
for name, lo, hi in [("lat", 0xC0, 0x24F), ("ext", 0x1E00, 0x1EFF)]:
    bases = [base_of(c) for c in range(lo, hi + 1)]
    pairs = sorted({x for x in bases if x and len(x) == 2})
    enc = ["0" if not x else (f"'{x}'" if len(x) == 1 else str(pairs.index(x) + 1)) for x in bases]
    out.append(f"// U+{lo:04X}..U+{hi:04X}: the letter without accents "
               f"(0: none{f', 1..{len(pairs)}: two letters from {name}_pairs' if pairs else ''})")
    out.append(f"static const char {name}_base[{hi - lo + 1}] = {{")
    for i in range(0, len(enc), 16):
        out.append("    " + ", ".join(enc[i:i + 16]) + ",")
    out.append("};")
    if pairs:
        out.append(f"static const char *const {name}_pairs[] = {{ " + ", ".join(f'"{p}"' for p in pairs) + " };")
    deltas = []
    for c in range(lo, hi + 1):
        low = chr(c).lower()
        deltas.append(ord(low) - c if len(low) == 1 else 0)
    out.append("// lower case: the code point plus this")
    out.append(f"static const int16_t {name}_lower[{hi - lo + 1}] = {{")
    for i in range(0, len(deltas), 16):
        out.append("    " + ", ".join(str(d) for d in deltas[i:i + 16]) + ",")
    out.append("};")
print("\n".join(out))
