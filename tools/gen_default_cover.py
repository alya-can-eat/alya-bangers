#!/usr/bin/env python3
"""Generate arm9/source/default_cover.c: the picture shown for songs without
a cover (purple dusk, mountains, a pale moon), 128x128 and 32x32, dithered to
BGR555 by dsconv's own cover code.

    python3 tools/gen_default_cover.py /path/to/dsconv/src > arm9/source/default_cover.c
"""
import io
import random
import sys

sys.path.insert(0, sys.argv[1])
from PIL import Image, ImageDraw  # noqa: E402
from dsconv.cover import _convert  # noqa: E402


def artwork():
    s = 512
    img = Image.new("RGB", (s, s))
    d = ImageDraw.Draw(img)
    for y in range(s):
        t = y / s
        top, bot = (34, 18, 74), (236, 122, 150)
        d.line([(0, y), (s, y)], fill=tuple(int(top[i] + (bot[i] - top[i]) * t ** 1.4) for i in range(3)))
    d.ellipse([300, 90, 460, 250], fill=(250, 226, 214))
    rnd = random.Random(3)
    for _ in range(90):
        d.point((rnd.randrange(s), rnd.randrange(0, 260)), fill=(255, 240, 250))
    for i in range(14):
        y = 340 + i * 12
        d.line([(0, y), (s, y)], fill=(250, 200, 200) if i % 2 else (120, 60, 120), width=3)
    d.polygon([(0, 330), (90, 250), (170, 300), (260, 220), (380, 330)], fill=(24, 12, 40))
    # the beach: lit by the moon, light enough to stand out from the dark UI
    d.rectangle([0, 430, s, s], fill=(104, 58, 104))
    d.rectangle([0, 430, s, 437], fill=(170, 104, 150))     # where the water meets the sand
    for _ in range(160):
        x, y = rnd.randrange(s), rnd.randrange(440, s)
        d.point((x, y), fill=(128, 76, 124))
    return img


buf = io.BytesIO()
artwork().save(buf, "PNG")
big, small = _convert(buf.getvalue())


def table(name, data):
    px = [data[i] | (data[i + 1] << 8) for i in range(0, len(data), 2)]
    lines = [", ".join(f"0x{v:04X}" for v in px[i:i + 12]) for i in range(0, len(px), 12)]
    return f"const uint16_t {name}[{len(px)}] = {{\n    " + ",\n    ".join(lines) + ",\n};\n"


print("// Generated by tools/gen_default_cover.py: shown for songs without a cover.")
print()
print('#include "default_cover.h"')
print()
print(table("default_cover", big))
print(table("default_thumb", small))
