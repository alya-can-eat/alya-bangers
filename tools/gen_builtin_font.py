#!/usr/bin/env python3
"""Generate arm9/source/builtin_font.c: glyphs the player always has, whether
or not font.bin contains them (ASCII, the UI symbols and icons).

    python3 tools/gen_builtin_font.py /path/to/dsconv/src > arm9/source/builtin_font.c

Glyphs come from GNU Unifont (via dsconv's copy); U+E000 is drawn here.
"""
import sys

sys.path.insert(0, sys.argv[1])
from dsconv.index import _load_font_data  # noqa: E402

UI = (
    "…·×–›→↳⇅★☆●○"   # … · × – › → ↳ ⇅ ★ ☆ ● ○
    "▶⏸⏭⏮ⓘ☰⋮⮟⮝♪�"       # ▶ ⏸ ⏭ ⏮ ⓘ ☰ ⋮ ⮟ ⮝ ♪ �
    "\U0001f500\U0001f501\U0001f502\U0001f5c0\U0001f50d\U0001f506"             # 🔀 🔁 🔂 🗀 🔍 🔆
)
QUEUE_ADD = [  # U+E000: add to queue (a list with a plus), bottom-aligned with ⏸ ⏭
    "................", "................", "................", "................",
    ".#########......", ".#########......", "................", ".#########......",
    ".#########.##...", "...........##...", ".######..######.", ".######..######.",
    "...........##...", "...........##...", "................", "................",
]
# U+E001..U+E004: brightness levels 2..5 (DS Lite): circle; sun; half full (split at 45°); full
SUNS = [
    [
        "................", "................", "................", "................",
        "................", "......###.......", ".....#...#......", "....#.....#.....",
        "....#.....#.....", "....#.....#.....", ".....#...#......", "......###.......",
        "................", "................", "................", "................",
    ],
    [
        "................", "................", ".......#........", "..#....#....#...",
        "...#.......#....", "......###.......", ".....#...#......", "....#.....#.....",
        ".##.#.....#.##..", "....#.....#.....", ".....#...#......", "......###.......",
        "...#.......#....", "..#....#....#...", ".......#........", "................",
    ],
    [
        "................", "................", ".......#........", "..#....#....#...",
        "...#.......#....", "......###.......", ".....#...#......", "....#...###.....",
        ".##.#..####.##..", "....#.#####.....", ".....#####......", "......###.......",
        "...#.......#....", "..#....#....#...", ".......#........", "................",
    ],
    [
        "................", "................", ".......#........", "..#....#....#...",
        "...#.......#....", "......###.......", ".....#####......", "....#######.....",
        ".##.#######.##..", "....#######.....", ".....#####......", "......###.......",
        "...#.......#....", "..#....#....#...", ".......#........", "................",
    ],
]

base, _jp, _comb = _load_font_data()
cps = sorted(set(range(0x20, 0x7F)) | {ord(c) for c in UI})
rows = []
for cp in cps:
    h = base[cp]
    width = 8 if len(h) == 32 else 16
    rows.append((cp, width, bytes.fromhex(h)))
qa = b"".join(int(r.replace("#", "1").replace(".", "0"), 2).to_bytes(2, "big") for r in QUEUE_ADD)
rows.append((0xE000, 16, qa))
for k, bitmap in enumerate(SUNS):
    b = b"".join(int(r.replace("#", "1").replace(".", "0"), 2).to_bytes(2, "big") for r in bitmap)
    rows.append((0xE001 + k, 16, b))
rows.sort()

print("// Generated by tools/gen_builtin_font.py from GNU Unifont (GPL-2.0-or-later with")
print("// font embedding exception). Glyphs the player always has: ASCII, UI symbols, icons.")
print()
print('#include "builtin_font.h"')
print()
print("const BuiltinGlyph builtin_glyphs[] = {")
for cp, w, b in rows:
    print(f"    {{ 0x{cp:04X}, {w}, {{ " + ", ".join(f"0x{x:02X}" for x in b) + " } },")
print("};")
print()
print("const int builtin_glyph_count = sizeof(builtin_glyphs) / sizeof(builtin_glyphs[0]);")
